# ---------------------------------------------------------------------------
def build_price_chart(enriched: pd.DataFrame, ticker: str, sessions: int = CHART_SESSIONS) -> str:
    """Render price/MA/Bollinger plus RSI and MACD panels; return a data URI.

    Three stacked panels sharing an x-axis, height-weighted 3:1:1 so the price
    action dominates. Reference lines at RSI 30/70 and MACD zero are what make
    the panels readable at a glance without a legend lookup.
    """
    window = enriched.iloc[-sessions:] if len(enriched) > sessions else enriched
    if window.empty:
        raise ValueError("Cannot chart an empty frame.")

    figure, (price_ax, rsi_ax, macd_ax) = plt.subplots(
        3, 1, figsize=(10, 8), sharex=True,
        gridspec_kw={"height_ratios": [3, 1, 1], "hspace": 0.08},
    )
    figure.patch.set_facecolor("white")

    # --- Panel 1: price, moving averages, Bollinger channel ---
    if {"bb_upper", "bb_lower"}.issubset(window.columns):
        price_ax.fill_between(
            window.index, window["bb_lower"], window["bb_upper"],
            color="#4a6fa5", alpha=0.10, label="Bollinger (20, 2)", zorder=1,
        )
    price_ax.plot(window.index, window["Close"], color="#1b2a41", linewidth=1.5, label="Close", zorder=4)
    for column, colour, label in (
        ("sma_50", "#d98324", "SMA-50"),
        ("sma_200", "#7b2d8e", "SMA-200"),
    ):
        if column in window.columns and window[column].notna().any():
            price_ax.plot(window.index, window[column], color=colour, linewidth=1.2,
                          label=label, alpha=0.9, zorder=3)

    price_ax.set_ylabel("Price", fontsize=9)
    price_ax.set_title(f"{ticker} - 12-month technical overview", fontsize=12,
                       fontweight="bold", loc="left", pad=10)
    price_ax.legend(loc="upper left", fontsize=8, framealpha=0.9, ncol=4)
    price_ax.grid(alpha=0.25, linewidth=0.6)

    # --- Panel 2: RSI with the conventional 30/70 bands ---
    if "rsi_14" in window.columns:
        rsi_ax.plot(window.index, window["rsi_14"], color="#2a6f97", linewidth=1.2)
        rsi_ax.axhline(70, color="#a32b2b", linestyle="--", linewidth=0.8, alpha=0.7)
        rsi_ax.axhline(30, color="#0f7b4f", linestyle="--", linewidth=0.8, alpha=0.7)
        rsi_ax.axhspan(30, 70, color="#cccccc", alpha=0.12)
        rsi_ax.set_ylim(0, 100)
        rsi_ax.set_yticks([0, 30, 50, 70, 100])
    rsi_ax.set_ylabel("RSI-14", fontsize=9)
    rsi_ax.grid(alpha=0.25, linewidth=0.6)

    # --- Panel 3: MACD with a signed histogram ---
    if {"macd", "macd_signal", "macd_hist"}.issubset(window.columns):
        macd_ax.plot(window.index, window["macd"], color="#1b2a41", linewidth=1.1, label="MACD")
        macd_ax.plot(window.index, window["macd_signal"], color="#d98324", linewidth=1.1, label="Signal")
        histogram = window["macd_hist"]
        macd_ax.bar(
            window.index, histogram, width=1.0, alpha=0.45,
            color=["#0f7b4f" if v >= 0 else "#a32b2b" for v in histogram.fillna(0)],
        )
        macd_ax.axhline(0, color="#555555", linewidth=0.8)
        macd_ax.legend(loc="upper left", fontsize=8, framealpha=0.9, ncol=2)
    macd_ax.set_ylabel("MACD", fontsize=9)
    macd_ax.grid(alpha=0.25, linewidth=0.6)

    macd_ax.xaxis.set_major_locator(mdates.MonthLocator(interval=2))
    macd_ax.xaxis.set_major_formatter(mdates.DateFormatter("%b %Y"))
    figure.autofmt_xdate(rotation=0, ha="center")

    for axis in (price_ax, rsi_ax, macd_ax):
        for spine in ("top", "right"):
            axis.spines[spine].set_visible(False)

    buffer = io.BytesIO()
    figure.savefig(buffer, format="png", dpi=130, bbox_inches="tight", facecolor="white")
    plt.close(figure)
    encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
    return f"data:image/png;base64,{encoded}"


