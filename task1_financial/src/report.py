def _format_currency(value: Any, currency: str = "USD") -> str:
    if value is None:
        return "n/a"
    symbol = {"USD": "$", "GBP": "£", "EUR": "€", "LKR": "Rs "}.get(currency, "")
    return f"{symbol}{value:,.2f}"


def _format_signed_pct(value: Any) -> tuple[str, str]:
    if value is None:
        return "n/a", "na"
    return f"{value:+.2f}%", ("pos" if value > 0 else "neg" if value < 0 else "")


def render_html_brief(
    equity: Any,
    analysis: Any,
    output_path: str | Path = "output/equity_brief.html",
) -> Path:
    """Render the complete brief to a single self-contained HTML file."""
    summary = equity.summary
    currency = summary.get("currency", "USD")

    ytd_text, ytd_class = _format_signed_pct(summary.get("ytd_return_pct"))
    below_high_text, _ = _format_signed_pct(summary.get("pct_below_52w_high"))

    snapshot_cells = [
        ("Current price", _format_currency(summary.get("current_price"), currency), ""),
        ("52-week high", _format_currency(summary.get("fifty_two_week_high"), currency), ""),
        ("52-week low", _format_currency(summary.get("fifty_two_week_low"), currency), ""),
        ("From 52w high", below_high_text, ""),
        ("YTD return", ytd_text, ytd_class),
        ("P/E ratio",
         f"{summary['pe_ratio']:.2f}" if summary.get("pe_ratio") else "n/a",
         "" if summary.get("pe_ratio") else "na"),
    ]

    rsi = summary.get("rsi_14")
    rsi_class = "neg" if rsi and rsi >= 70 else "pos" if rsi and rsi <= 30 else ""
    histogram = summary.get("macd_histogram")

    technical_cells = [
        ("SMA-50", _format_currency(summary.get("sma_50"), currency), ""),
        ("SMA-200", _format_currency(summary.get("sma_200"), currency), ""),
        ("RSI-14", f"{rsi:.1f}" if rsi is not None else "n/a", rsi_class),
        ("MACD histogram",
         f"{histogram:+.3f}" if histogram is not None else "n/a",
         "pos" if histogram and histogram > 0 else "neg" if histogram else ""),
        ("Bollinger %B",
         f"{summary['bollinger_pct_b']:.2f}" if summary.get("bollinger_pct_b") is not None else "n/a", ""),
        ("Momentum screen",
         str(summary.get("momentum_signal", "n/a")).replace("_", " ").title(),
         "pos" if (summary.get("momentum_score") or 0) > 0 else "neg" if (summary.get("momentum_score") or 0) < 0 else ""),
        ("Annualised vol (30d)",
         f"{summary['annualised_volatility_30d'] * 100:.1f}%"
         if summary.get("annualised_volatility_30d") is not None else "n/a", ""),
    ]

    top_headlines: Sequence[Any] = sorted(
        analysis.headline_sentiments, key=lambda h: h.confidence, reverse=True
    )[:3]

    models = analysis.model_manifest.get("providers", []) if analysis.model_manifest else []
    model_label = f"{models[0]['provider']}/{models[0]['model']}" if models else "n/a"
    prompt_label = ", ".join(f"{p['name']} {p['version']}" for p in analysis.prompt_versions) or "n/a"

    environment = Environment(autoescape=select_autoescape(["html"]))
    html = environment.from_string(_TEMPLATE).render(
        s=summary,
        signal=analysis.signal,
        is_fallback=analysis.signal_is_fallback,
        aggregate=analysis.aggregate,
        top_headlines=top_headlines,
        snapshot_cells=snapshot_cells,
        technical_cells=technical_cells,
        chart_uri=build_price_chart(equity.prices, equity.ticker),
        warnings=equity.warnings,
        disclaimer=RISK_DISCLAIMER,
        rec_colour=RECOMMENDATION_COLOURS.get(
            analysis.signal.recommendation.value if analysis.signal else "Hold", "#5b6b7f"
        ),
        generated_at=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        model_label=model_label,
        prompt_label=prompt_label,
    )

    destination = Path(output_path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(html, encoding="utf-8")
    logger.info("Brief written to %s (%.1f KB).", destination, destination.stat().st_size / 1024)
    return destination


def render_markdown_brief(
    equity: Any, analysis: Any, output_path: str | Path = "output/equity_brief.md"
) -> Path:
    """Markdown variant. The brief allows Markdown; HTML is the richer artefact,
    but Markdown renders natively on GitHub, so both are produced."""
    summary, signal, aggregate = equity.summary, analysis.signal, analysis.aggregate
    lines = [
        f"# {summary.get('company_name')} ({summary.get('ticker')}) - Equity Research Brief",
        "",
        f"*Data as at {summary.get('as_of')} · {summary.get('sessions_analysed')} sessions analysed*",
        "",
        "## Recommendation",
        "",
    ]
    if signal:
        lines += [
            f"**{signal.recommendation.value}** — model confidence {signal.confidence:.0%}"
            + ("  \n> ⚠️ Rules-based fallback: LLM output failed validation." if analysis.signal_is_fallback else ""),
            "", f"> {signal.justification}", "",
            "**Key drivers**", "", *[f"- {d}" for d in signal.key_drivers], "",
            "**Risks to this view**", "", *[f"- {r}" for r in signal.risks], "",
        ]

    lines += [
        "## Company snapshot", "",
        "| Metric | Value |", "|---|---|",
        f"| Current price | {_format_currency(summary.get('current_price'), summary.get('currency','USD'))} |",
        f"| 52-week high | {_format_currency(summary.get('fifty_two_week_high'), summary.get('currency','USD'))} |",
        f"| 52-week low | {_format_currency(summary.get('fifty_two_week_low'), summary.get('currency','USD'))} |",
        f"| YTD return | {_format_signed_pct(summary.get('ytd_return_pct'))[0]} |",
        f"| P/E ratio | {summary.get('pe_ratio') or 'n/a'} |",
        "", "## Technical outlook", "",
        "| Indicator | Value |", "|---|---|",
        f"| SMA-50 | {summary.get('sma_50') or 'n/a'} |",
        f"| SMA-200 | {summary.get('sma_200') or 'n/a'} |",
        f"| RSI-14 | {summary.get('rsi_14') or 'n/a'} |",
        f"| MACD histogram | {summary.get('macd_histogram') or 'n/a'} |",
        f"| Bollinger %B | {summary.get('bollinger_pct_b') or 'n/a'} |",
        f"| Momentum screen | {summary.get('momentum_signal')} ({summary.get('momentum_score')}) |",
        "",
        *[f"- {line}" for line in summary.get("momentum_rationale", [])],
        "", "## News sentiment", "",
    ]
    if aggregate:
        lines += [
            f"Aggregate **{aggregate.label.value}** ({aggregate.score:+.2f}) across "
            f"{aggregate.headline_count} headlines — {aggregate.positive_count} positive, "
            f"{aggregate.neutral_count} neutral, {aggregate.negative_count} negative.", "",
            "| Sentiment | Confidence | Headline |", "|---|---|---|",
        ]
        for item in sorted(analysis.headline_sentiments, key=lambda h: h.confidence, reverse=True)[:3]:
            safe = item.headline.replace("|", "\\|")
            lines.append(f"| {item.sentiment.value} | {item.confidence:.2f} | {safe} |")
    else:
        lines.append("*No headline sentiment available.*")

    lines += ["", "---", "", f"> **RISK DISCLAIMER** — {RISK_DISCLAIMER}", ""]

    destination = Path(output_path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines), encoding="utf-8")
    return destination
